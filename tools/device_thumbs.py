"""Make the small project pictures for the resume badge's resume pages.

Each homepage card image is cropped to a square (centered, like the cards),
shrunk to THUMB x THUMB pixels, and written as RGB565 arrays to
device/resume_badge/thumbs.h, which the sketch draws in the top-right corner.

    python3 tools/device_thumbs.py
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "device" / "resume_badge" / "thumbs.h"
THUMB = 48
BG = (16, 20, 40)   # page background (0x10A5), shows through transparent PNGs

# C name -> homepage image (same order as the resume pages)
IMAGES = {
    "THUMB_ACCELIRATE": "media/experience/accelirate-logo.png",
    "THUMB_SOILNODE":   "media/soilnode/pcb-3d-view.png",
    "THUMB_MOTOR":      "media/ruhart/motordriver-schematic.png",
    "THUMB_BREATHE":    "media/breathe/interview-scary.jpg",
    "THUMB_LIDAR":      "media/ruhart/lidarbot.jpeg",
}


def to_565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def thumb(path):
    im = Image.open(ROOT / path).convert("RGBA")
    flat = Image.new("RGBA", im.size, BG + (255,))
    flat.alpha_composite(im)
    w, h = flat.size
    side = min(w, h)
    box = ((w - side) // 2, (h - side) // 2, (w + side) // 2, (h + side) // 2)
    return flat.convert("RGB").crop(box).resize((THUMB, THUMB), Image.LANCZOS)


def main():
    lines = [
        "// Generated by tools/device_thumbs.py - project pictures for the resume pages.",
        "#pragma once",
        "#include <stdint.h>",
        f"#define THUMB {THUMB}",
        "",
    ]
    previews = []
    for name, path in IMAGES.items():
        im = thumb(path)
        previews.append(im)
        px = [to_565(*im.getpixel((x, y))) for y in range(THUMB) for x in range(THUMB)]
        lines.append(f"// {path}")
        lines.append(f"const uint16_t {name}[THUMB * THUMB] PROGMEM = {{")
        for i in range(0, len(px), 16):
            lines.append("  " + ",".join(f"0x{v:04X}" for v in px[i:i + 16]) + ",")
        lines.append("};\n")
    OUT.write_text("\n".join(lines))

    sheet = Image.new("RGB", (len(previews) * (THUMB + 8), THUMB), BG)
    for i, im in enumerate(previews):
        sheet.paste(im, (i * (THUMB + 8), 0))
    sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(
        ROOT / "device" / "previews" / "thumbs.png")
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
